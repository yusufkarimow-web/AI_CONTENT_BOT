async def generate_ai_content(
    topic: str,
    niche: str,
    language: str = "ru",
    content_type: str = "reels",
    use_best_hook: bool = True
) -> str:
    """
    Генерация AI-контента с вирусными хуками и локальным контекстом

    Args:
        topic: Тема контента
        niche: Ключ ниши (cafe, beauty, shop, auto, etc.)
        language: "ru" или "tg"
        content_type: "reels", "post", "stories", "ideas", "hook", "caption"
        use_best_hook: Использовать лучший хук из библиотеки

    Returns:
        str: Готовый контент
    """

    # 1. Выбираем вирусный хук
    hook = ""
    if use_best_hook:
        hook = select_viral_hook(niche, language)
    else:
        hook = topic  # Используем тему как хук

    # 2. Формируем промпты
    system_prompt = get_system_prompt(niche, language, content_type)
    content_prompt = get_content_prompt(topic, niche, language, content_type, hook)

    # 3. Генерируем через AI
    try:
        # Пробуем новый генератор (если OpenAI API настроен)
        if OPENAI_API_KEY:
            from services.openai_service import generate_content
            content = generate_content(
                system_prompt=system_prompt,
                user_prompt=content_prompt,
                model=OPENAI_MODEL
            )
        else:
            # Fallback: используем legacy генератор
            content = generate_content_legacy(
                topic=topic,
                niche=niche
            )
    except Exception as e:
        # Если AI не работает — используем шаблон
        content = generate_template_content(topic, niche, language, content_type, hook)

    # 4. Пост-обработка
    content = post_process_content(content, language, niche)

    return content


def select_viral_hook(niche: str, language: str) -> str:
    """
    Выбирает лучший вирусный хук для ниши
    Использует weighted random на основе CTR
    """
    hooks = VIRAL_HOOKS_LIBRARY.get(language, VIRAL_HOOKS_LIBRARY["ru"]).get(niche, [])

    if not hooks:
        # Fallback на общие хуки
        hooks = VIRAL_HOOKS_LIBRARY.get(language, VIRAL_HOOKS_LIBRARY["ru"]).get("other", [])

    # Weighted random по CTR
    total_ctr = sum(h["ctr"] for h in hooks)
    weights = [h["ctr"] / total_ctr for h in hooks]

    selected = random.choices(hooks, weights=weights, k=1)[0]
    return selected["hook"]


