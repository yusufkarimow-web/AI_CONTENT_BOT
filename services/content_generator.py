def post_process_content(content: str, language: str, niche: str) -> str:
    """Финальная обработка контента перед отправкой"""

    # Убираем лишние пробелы
    content = content.strip()

    # Добавляем эмодзи, если их мало
    if content.count("🔥") + content.count("✅") + content.count("💡") < 3:
        # Контент слишком сухой — добавляем визуал
        pass  # AI должен сам добавлять, но можно усилить

    # Проверяем длину
    if len(content) < 100:
        content += "\n\n💡 Добавьте больше деталей для лучшего результата."

    # Добавляем призыв к действию, если нет
    ctas_ru = ["подпишитесь", "комментарий", "сохраните", "поделитесь", "напишите"]
    ctas_tg = ["обуна шавед", "шарҳ", "нигоҳ доред", "мубодила кунед", "нависед"]

    has_cta = any(cta in content.lower() for cta in (ctas_ru if language == "ru" else ctas_tg))
    if not has_cta:
        if language == "tg":
            content += "\n\n👇 Фикру мулоҳизаҳои худро дар шарҳҳо нависед!"
        else:
            content += "\n\n👇 Напишите свои мысли в комментариях!"

    return content


